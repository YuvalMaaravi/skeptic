export const catalog: CatalogItem[] = [...entries, ...shelfItems, ...clinicListings].map((item) => ({
  ...item,
  ...(pricePatches[item.id] ? { price: pricePatches[item.id] } : {}),
  ...(extras[item.id] ? { extra: extras[item.id] } : {}),
  ...(photos[item.id] ? { photos: photos[item.id] } : {}),
}));

for (const id of [...Object.keys(pricePatches), ...Object.keys(extras), ...Object.keys(photos)]) {
  if (!catalog.some((item) => item.id === id)) {
    throw new Error(`Patch for unknown id: ${id}`);
  }
}

const ids = new Set<string>();
for (const item of catalog) {
  if (ids.has(item.id)) {
    throw new Error(`Duplicate catalog id: ${item.id}`);
  }
  ids.add(item.id);
  if (item.sources.length === 0) {
    throw new Error(`Missing sources: ${item.id}`);
  }
  if (!item.summary.trim() || !item.skeptic.trim()) {
    throw new Error(`Thin entry: ${item.id}`);
  }
}
for (const item of catalog) {
  for (const related of item.related ?? []) {
    if (!ids.has(related)) {
      throw new Error(`Missing related id ${related} on ${item.id}`);
    }
  }
}

export const catalogById = new Map(catalog.map((item) => [item.id, item]));
